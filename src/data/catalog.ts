function buildProduct(
  bp: Blueprint,
  categoryId: string,
  index: number,
  rng: ReturnType<typeof makeRng>,
): Product {
  const now = Date.now()
  const onSale = rng.bool(0.34)
  const discount = onSale ? rng.pick([0.1, 0.15, 0.2, 0.25, 0.3, 0.4]) : 0
  const id = `p-${categoryId.slice(2)}-${String(index + 1).padStart(2, '0')}`
  const rating = Math.round(rng.float(3.6, 5) * 10) / 10
  const reviewCount = rng.int(12, 940)
  const createdDaysAgo = rng.int(4, 620)
  const featured = rng.bool(0.18)

  return {
    id,
    slug: `${bp.brand}-${bp.name}`
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, ''),
    name: bp.name,
    brand: bp.brand,
    categoryId,
    price: Math.round(bp.price * 100) / 100,
    compareAtPrice: onSale ? Math.round(bp.price * (1 + discount) * 100) / 100 : null,
    cost: Math.round(bp.price * rng.float(0.42, 0.68) * 100) / 100,
    sku: `${categoryId.slice(2, 5).toUpperCase()}-${String(index + 1).padStart(3, '0')}${rng.pick(['A', 'B', 'C', 'S'])}`,
    stock: rng.bool(0.07) ? 0 : rng.int(3, 480),
    rating,
    reviewCount,
    sold: rng.int(40, 9800),
    status: rng.bool(0.06) ? 'draft' : 'active',
    tagline: bp.tagline,
    description: `${bp.name} from ${bp.brand} is built for people who use their gear every day and expect it to keep working. ${bp.tagline} Every unit is covered by a two-year limited warranty, ships free over RWF 50, and can be returned within 30 days of delivery.`,
    highlights: bp.highlights,
    specs: bp.specs.map(([label, value]) => ({ label, value })),
    tags: [...bp.tags, ...(featured ? ['featured'] : [])],
    colors: rng.bool(0.5) ? bp.colors : STOCK_COLORS.slice(0, rng.int(2, 4)),
    createdAt: new Date(now - createdDaysAgo * 86400000).toISOString(),
    featured,
  }
}

export const products: Product[] = categories.flatMap((cat) =>
  (blueprints[cat.id] ?? []).map((bp, i) => buildProduct(bp, cat.id, i, makeRng(9271 + i * 31 + cat.id.length * 7))),
)
